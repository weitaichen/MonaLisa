// Writes tests/harness/b2/baseline/: the pre-美體 engine (index.ts, pipeline.ts and passes/reshape.ts at commit
// 25d1768, or $B2_BASE) with imports pointed back at src/, so the harness can prove the face chain is
// bit-identical with no body field. Every other engine module is shared with the current tree.
import { execFileSync } from 'node:child_process';
import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, '..', '..', '..');
const out = join(here, 'baseline');
mkdirSync(out, { recursive: true });
const SRC = '../../../../src';
const show = (path) => execFileSync('git', ['show', `${process.env.B2_BASE ?? '25d1768'}:${path}`], { cwd: root, encoding: 'utf8' });

const files = {
  'index.ts': [show('src/engine/index.ts'), { "'../types'": `'${SRC}/types'`, "'./gl/gl'": `'${SRC}/engine/gl/gl'`, "'./uniforms'": `'${SRC}/engine/uniforms'` }],
  'pipeline.ts': [
    show('src/engine/pipeline.ts'),
    {
      "'../types'": `'${SRC}/types'`,
      "'./gl/gl'": `'${SRC}/engine/gl/gl'`,
      "'./passes/reshape'": "'./reshape'",
      "'./passes/": `'${SRC}/engine/passes/`,
      "'./shaders/": `'${SRC}/engine/shaders/`,
      "'./uniforms'": `'${SRC}/engine/uniforms'`,
    },
  ],
  'reshape.ts': [
    show('src/engine/passes/reshape.ts'),
    { "'../../types'": `'${SRC}/types'`, "'../params'": `'${SRC}/engine/params'`, "'../gl/gl'": `'${SRC}/engine/gl/gl'`, "'./faceMesh'": `'${SRC}/engine/passes/faceMesh'` },
  ],
};
for (const [name, [text, map]] of Object.entries(files)) {
  let s = `// GENERATED by make-baseline.mjs from git ${process.env.B2_BASE ?? '25d1768'} — do not edit\n${text}`;
  for (const [a, b] of Object.entries(map)) s = s.split(a).join(b);
  writeFileSync(join(out, name), s);
}
console.log(`baseline engine written to ${out}`);
